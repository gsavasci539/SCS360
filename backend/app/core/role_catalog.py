def institution_roles(organization_id, permissions, existing=()):
    """Create missing local templates; never edit an existing custom role."""
    from app.infrastructure.models.models import Role
    known = set(existing)
    return [Role(organization_id=organization_id, name=name, slug=slug,
        permissions=[permission for permission in permissions if permission.code in default_permissions(slug)])
        for slug, name in ROLE_NAMES.items() if slug not in known]


def default_permissions(slug):
    codes = set(PERMISSION_CODES)
    if slug in {"org_admin", "owner"}:
        return codes
    if slug == "branch_manager":
        return {code for code in codes if not code.startswith(("hq.", "role.", "roles.")) and code not in {
            "org.write", "branch.write", "settings.write", "settings.update", "users.assign_branches", "users.assign_roles", "guidance.read_confidential"}}
    prefixes = {
        "teacher": ("teacher.", "academic.", "homework.", "daily_reports.", "material.", "timetable.", "exam.", "tutoring.", "messaging."),
        "accountant": ("finance.", "payments.", "receipt.", "report."),
        "canteen_staff": ("canteen.",),
        "parent": ("parent.",),
        "security": ("security.", "dismissal."),
        "librarian": ("library.",),
        "transport_staff": ("bus.", "transport."),
        "staff": (),
    }.get(slug, ())
    selected = {code for code in codes if code.startswith(prefixes)} if prefixes else set()
    extra = {
        "teacher": {"students.read", "classes.read", "parents.read", "announcement.read", "health.read", "clubs.read"},
        "accountant": {"students.read", "parents.read", "dashboard.read"},
        "canteen_staff": {"students.read"},
        "security": {"students.read"},
        "librarian": {"students.read"},
        "transport_staff": {"students.read"},
        "staff": {"students.read", "attendance.read", "parent_notices.read"},
    }.get(slug, set())
    if slug in {"teacher", "accountant", "canteen_staff", "security", "librarian", "transport_staff", "staff"}:
        extra = extra | {"surveys.respond"}
    return selected | extra
